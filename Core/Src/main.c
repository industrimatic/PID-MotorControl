void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
  if (huart == &huart1)
  {
    float val = 0.f;
    if (sscanf(message, "kp=%f\n", &val) == 1)
    {
      Motor.kp = val;
      HAL_UART_Transmit_DMA(&huart1, "kp set", 7);
    }
    else if (sscanf(message, "ki=%f\n", &val) == 1)
    {
      Motor.ki = val;
      HAL_UART_Transmit_DMA(&huart1, "ki set", 7);
    }
    else if (sscanf(message, "kd=%f\n", &val) == 1)
    {
      Motor.kd = val;
      HAL_UART_Transmit_DMA(&huart1, "kd set", 7);
    }

    else if (sscanf(message, "pos_kp=%f\n", &val) == 1)
    {
      Motor.pos_kp = val;
      HAL_UART_Transmit_DMA(&huart1, "pos kp set", 11);
    }
    else if (sscanf(message, "pos_ki=%f\n", &val) == 1)
    {
      Motor.pos_ki = val;
      HAL_UART_Transmit_DMA(&huart1, "pos ki set", 11);
    }
    else if (sscanf(message, "pos_kd=%f\n", &val) == 1)
    {
      Motor.pos_kd = val;
      HAL_UART_Transmit_DMA(&huart1, "pos kd set", 11);
    }

    else if (sscanf(message, "speed=%f\n", &val) == 1)
    {
      PID_Motor_Set_Target(&Motor, val);
      HAL_UART_Transmit_DMA(&huart1, "speed set", 10);
    }
    else if (sscanf(message, "pos=%f\n", &val) == 1)
    {
      PID_Motor_Set_Pos(&Motor, val);
      HAL_UART_Transmit_DMA(&huart1, "position set", 13);
    }

    HAL_UARTEx_ReceiveToIdle_DMA(&huart1, (uint8_t *)message, sizeof(message));
    __HAL_DMA_DISABLE_IT(&hdma_usart1_rx, DMA_IT_HT);
  }
}

